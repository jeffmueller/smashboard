#!/usr/bin/env ruby
# frozen_string_literal: true

# Regenerates app/javascript/emoji_data.js from the Unicode emoji test file.
#
#   curl -o emoji-test.txt https://unicode.org/Public/emoji/latest/emoji-test.txt
#   ruby script/generate_emoji_data.rb emoji-test.txt
#
# The picker ships the data rather than fetching it, so it works offline and
# doesn't tell anyone which emoji a user is browsing. Skin-tone variants are
# dropped: they multiply the list roughly fivefold to pick an icon that renders
# at 16px, and the base emoji is already there.
source = ARGV[0] || abort('usage: generate_emoji_data.rb <emoji-test.txt>')
out = File.expand_path('../app/javascript/emoji_data.js', __dir__)

groups = []
group = nil
version = nil

File.foreach(source) do |line|
  version ||= line[/^# Version: (.+)$/, 1]

  if (name = line[/^# group: (.+)$/, 1])
    # Skin tones and hair colours on their own aren't icons anyone picks.
    group = name == 'Component' ? nil : { name: name, emoji: [] }
    groups << group if group
    next
  end

  next if group.nil? || line.start_with?('#') || line.strip.empty?

  status, comment = line.split(';', 2)&.last.to_s.split('#', 2)
  next unless status.to_s.strip == 'fully-qualified'

  # "😀 E1.0 grinning face" — the emoji, the version it landed in, then the name.
  char, name = comment.to_s.strip.split(/\s+E\d+(?:\.\d+)?\s+/, 2)
  next if char.nil? || char.empty? || name.nil? || name.empty?
  next if name.include?('skin tone')

  group[:emoji] << [char, name]
end

body = groups.map do |g|
  entries = g[:emoji].map { |char, name| "[#{char.dump},#{name.dump}]" }.join(',')
  "  { name: #{g[:name].dump}, emoji: [#{entries}] }"
end.join(",\n")

File.write(out, <<~JS)
  // Generated by script/generate_emoji_data.rb — do not edit by hand.
  // Source: https://unicode.org/Public/emoji/latest/emoji-test.txt (Unicode #{version})
  export const EMOJI_GROUPS = [
  #{body}
  ]
JS

total = groups.sum { |g| g[:emoji].size }
puts "wrote #{out}: #{groups.size} groups, #{total} emoji"
