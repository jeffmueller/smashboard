#!/bin/bash

# smashboard - One-time Raspberry Pi setup.
#
# Creates the Postgres databases, the systemd units, the nginx site and the
# SSL certificate. Safe to re-run: everything here checks before it creates,
# and the secrets in ~/smashboard/.env are generated once and never replaced.
#
# Prerequisites on the Pi: nginx, postgresql, certbot, rbenv with Ruby 3.4.7.

set -euo pipefail

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; BLUE='\033[0;34m'; NC='\033[0m'
print_status()  { echo -e "${BLUE}[INFO]${NC} $1"; }
print_success() { echo -e "${GREEN}[SUCCESS]${NC} $1"; }
print_warning() { echo -e "${YELLOW}[WARNING]${NC} $1"; }
print_error()   { echo -e "${RED}[ERROR]${NC} $1"; }

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
[ -f "$SCRIPT_DIR/.env.deploy" ] && source "$SCRIPT_DIR/.env.deploy"

PI_USER=${PI_USER:-pi}
PI_HOST=${PI_HOST:-raspberrypi.local}
DOMAIN_NAME=${DOMAIN_NAME:-dashboard.example.com}
APP_PORT=${APP_PORT:-3012}
RUBY_VERSION=3.4.7
SKIP_SSL=false

while [[ $# -gt 0 ]]; do
    case $1 in
        --skip-ssl) SKIP_SSL=true; shift ;;
        --help)
            echo "Usage: $0 [--skip-ssl]"
            echo "  --skip-ssl   Set everything up but don't request a certificate."
            echo "Environment (or .env.deploy): PI_USER, PI_HOST, DOMAIN_NAME, APP_PORT"
            exit 0 ;;
        *) print_error "Unknown option: $1"; exit 1 ;;
    esac
done

print_status "═══════════════════════════════════════════════"
print_status "  smashboard - Raspberry Pi setup"
print_status "═══════════════════════════════════════════════"
print_status "Target:  $PI_USER@$PI_HOST"
print_status "Domain:  $DOMAIN_NAME"
print_status "Port:    $APP_PORT"
print_status "SSL:     $([ "$SKIP_SSL" = true ] && echo 'skipped' || echo "certbot for $DOMAIN_NAME")"
print_status "═══════════════════════════════════════════════"
echo ""

if ! ssh -o ConnectTimeout=8 -o BatchMode=yes "$PI_USER@$PI_HOST" exit 2>/dev/null; then
    print_error "Cannot reach $PI_USER@$PI_HOST over SSH"
    exit 1
fi

# A certificate can only be issued for a name that resolves to this machine, and
# a failed ACME attempt counts against Let's Encrypt's rate limit. Check first.
if [ "$SKIP_SSL" = false ]; then
    if ! getent hosts "$DOMAIN_NAME" > /dev/null 2>&1; then
        print_error "$DOMAIN_NAME does not resolve."
        print_error "Add the DNS record first, or re-run with --skip-ssl."
        exit 1
    fi
    print_success "$DOMAIN_NAME resolves to $(getent hosts "$DOMAIN_NAME" | awk '{print $1}' | head -1)"
fi

print_status "Uploading nginx config..."
sed -e "s|__DOMAIN_NAME__|$DOMAIN_NAME|g" \
    -e "s|__APP_PORT__|$APP_PORT|g" \
    -e "s|__PI_USER__|$PI_USER|g" \
    "$SCRIPT_DIR/conf/nginx.conf" > /tmp/smashboard-nginx.conf
scp -q /tmp/smashboard-nginx.conf "$PI_USER@$PI_HOST":~/smashboard-nginx.conf
rm -f /tmp/smashboard-nginx.conf

ssh "$PI_USER@$PI_HOST" "bash -s" << ENDSSH
set -euo pipefail

APP_PORT=$APP_PORT
DOMAIN_NAME=$DOMAIN_NAME
PI_USER=$PI_USER
RUBY_VERSION=$RUBY_VERSION
SKIP_SSL=$SKIP_SSL

echo "── Directories ──────────────────────────────────────"
mkdir -p ~/smashboard/app ~/smashboard/backups ~/smashboard/shared/storage

echo "── Ruby ─────────────────────────────────────────────"
RBENV_ROOT="\$HOME/.rbenv"
RUBY_BIN="\$RBENV_ROOT/versions/\$RUBY_VERSION/bin"
if [ ! -x "\$RUBY_BIN/ruby" ]; then
    echo "ERROR: Ruby \$RUBY_VERSION not found at \$RUBY_BIN" >&2
    echo "Install it with: rbenv install \$RUBY_VERSION" >&2
    exit 1
fi
echo "Using \$(\$RUBY_BIN/ruby -v)"

echo "── Databases ────────────────────────────────────────"
# Peer auth over the unix socket as this user; no password anywhere.
for db in smashboard_production smashboard_production_cache smashboard_production_queue smashboard_production_cable; do
    if psql -lqtA -F: 2>/dev/null | cut -d: -f1 | grep -qx "\$db"; then
        echo "  \$db (exists)"
    else
        createdb "\$db" && echo "  \$db (created)"
    fi
done

echo "── Secrets ──────────────────────────────────────────"
ENV_FILE=\$HOME/smashboard/.env
# Generated once and never regenerated: rotating SECRET_KEY_BASE signs every
# session out, rotating the VAPID keys silently breaks every push subscription,
# and rotating the Active Record encryption keys makes every stored credential
# undecryptable.
if [ ! -f "\$ENV_FILE" ]; then
    umask 077
    HEX() { \$RUBY_BIN/ruby -rsecurerandom -e 'print SecureRandom.hex(32)'; }
    ALNUM() { \$RUBY_BIN/ruby -rsecurerandom -e 'print SecureRandom.alphanumeric(32)'; }
    cat > "\$ENV_FILE" << ENVEOF
# smashboard production environment. Generated by setup-pi.sh; never committed.
# Rotating any key below has consequences — see the comments in setup-pi.sh.
RAILS_ENV=production
APP_HOST=\$DOMAIN_NAME
PORT=\$APP_PORT
RAILS_MAX_THREADS=5
RAILS_LOG_LEVEL=info
# Loopback only — nginx is the way in, and 0.0.0.0 would expose the app
# unproxied on the LAN.
BIND_HOST=127.0.0.1

SECRET_KEY_BASE=\$(HEX)

ACTIVE_RECORD_ENCRYPTION_PRIMARY_KEY=\$(ALNUM)
ACTIVE_RECORD_ENCRYPTION_DETERMINISTIC_KEY=\$(ALNUM)
ACTIVE_RECORD_ENCRYPTION_KEY_DERIVATION_SALT=\$(ALNUM)

# Postgres over the local socket as \$PI_USER (peer auth), so no password.
SMASHBOARD_DATABASE_HOST=/var/run/postgresql
SMASHBOARD_DATABASE_PORT=5432
SMASHBOARD_DATABASE_USER=\$PI_USER
SMASHBOARD_DATABASE_PASSWORD=

# Web push. Filled in by deploy.sh once the gems are installed.
VAPID_SUBJECT=mailto:admin@\$DOMAIN_NAME
VAPID_PUBLIC_KEY=
VAPID_PRIVATE_KEY=
ENVEOF
    chmod 600 "\$ENV_FILE"
    echo "  created \$ENV_FILE (mode 600)"
else
    echo "  \$ENV_FILE exists — left untouched"
fi

echo "── systemd ──────────────────────────────────────────"
# Two units: Puma serves, and a separate Solid Queue supervisor runs the
# recurring sweeps and every panel refresh. Split rather than SOLID_QUEUE_IN_PUMA
# so a wedged integration fetch can't take the web server down with it, and so
# either half can be restarted alone.
sudo tee /etc/systemd/system/smashboard-web.service > /dev/null << UNITEOF
[Unit]
Description=smashboard web (Puma)
After=network.target postgresql.service
Requires=postgresql.service

[Service]
Type=simple
User=\$PI_USER
WorkingDirectory=/home/\$PI_USER/smashboard/app
EnvironmentFile=/home/\$PI_USER/smashboard/.env
Environment=PATH=\$RUBY_BIN:/usr/local/bin:/usr/bin:/bin
# No -p/-b here: config/puma.rb binds from PORT and BIND_HOST, and a second
# bind on the command line makes Puma open the port twice and die on the
# duplicate. BIND_HOST=127.0.0.1 in the env file keeps this off the LAN.
ExecStart=\$RUBY_BIN/bundle exec puma
Restart=always
RestartSec=5
StandardOutput=append:/home/\$PI_USER/smashboard/app/log/production.log
StandardError=append:/home/\$PI_USER/smashboard/app/log/production.log

[Install]
WantedBy=multi-user.target
UNITEOF

sudo tee /etc/systemd/system/smashboard-jobs.service > /dev/null << UNITEOF
[Unit]
Description=smashboard jobs (Solid Queue)
After=network.target postgresql.service smashboard-web.service
Requires=postgresql.service

[Service]
Type=simple
User=\$PI_USER
WorkingDirectory=/home/\$PI_USER/smashboard/app
EnvironmentFile=/home/\$PI_USER/smashboard/.env
Environment=PATH=\$RUBY_BIN:/usr/local/bin:/usr/bin:/bin
ExecStart=\$RUBY_BIN/bundle exec bin/jobs
Restart=always
RestartSec=5
StandardOutput=append:/home/\$PI_USER/smashboard/app/log/jobs.log
StandardError=append:/home/\$PI_USER/smashboard/app/log/jobs.log

[Install]
WantedBy=multi-user.target
UNITEOF

sudo systemctl daemon-reload
sudo systemctl enable smashboard-web smashboard-jobs > /dev/null 2>&1
echo "  smashboard-web and smashboard-jobs enabled"

echo "── nginx ────────────────────────────────────────────"
HAS_CERT=false
sudo test -f /etc/letsencrypt/live/\$DOMAIN_NAME/fullchain.pem && HAS_CERT=true

if [ "\$HAS_CERT" = false ] && [ "\$SKIP_SSL" = false ]; then
    # The real config references a certificate that doesn't exist yet, and nginx
    # refuses to start with a missing cert — so stand up an HTTP-only site just
    # long enough for the ACME challenge, then swap in the real one.
    echo "  installing temporary HTTP site for the ACME challenge"
    sudo mkdir -p /var/www/html
    sudo tee /etc/nginx/sites-available/smashboard > /dev/null << TMPEOF
server {
    listen 80;
    server_name \$DOMAIN_NAME;
    location /.well-known/acme-challenge/ { root /var/www/html; }
    location / { return 200 'smashboard: awaiting certificate'; add_header Content-Type text/plain; }
}
TMPEOF
    sudo ln -sfn /etc/nginx/sites-available/smashboard /etc/nginx/sites-enabled/smashboard
    sudo nginx -t && sudo systemctl reload nginx

    echo "  requesting certificate for \$DOMAIN_NAME"
    # --webroot rather than --nginx: the nginx installer rewrites the site file,
    # and the real config below is not something certbot should be editing.
    sudo certbot certonly --webroot -w /var/www/html -d "\$DOMAIN_NAME" \
        --non-interactive --agree-tos --register-unsafely-without-email
    HAS_CERT=true
fi

if [ "\$HAS_CERT" = true ]; then
    sudo mv ~/smashboard-nginx.conf /etc/nginx/sites-available/smashboard
    sudo ln -sfn /etc/nginx/sites-available/smashboard /etc/nginx/sites-enabled/smashboard
    sudo nginx -t
    sudo systemctl reload nginx
    echo "  HTTPS site live"
else
    rm -f ~/smashboard-nginx.conf
    echo "  no certificate — nginx not configured (re-run without --skip-ssl)"
fi

echo ""
echo "Setup complete."
ENDSSH

print_success "Pi setup complete"
echo ""
print_status "Next: ./deployment/deploy.sh --migrate"
